def demo_parts() -> list[Part]:
    parts: list[Part] = []
    for mark, layer, b, shape, n in SAMPLE:
        poly = rect(*shape) if isinstance(shape, tuple) else shape
        L = max(p[0] for p in poly)
        for i in range(n):
            # каждый третий экземпляр — зеркальный и сдвинутый, как в модели
            if i % 3 == 1:
                pts = [(L - x + 1000, y + 500) for x, y in poly]
            else:
                pts = list(poly)
            parts.append(Part(uid=f"{mark}#{i}", layer=layer, b=b, outline=pts, source="demo"))
    return parts
